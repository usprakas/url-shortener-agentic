create table links (
  id bigint generated by default as identity primary key, code varchar(12) not null, original_url varchar(2048) not null, created_at timestamp with time zone not null, expires_at timestamp with time zone, idempotency_key varchar(128), deleted boolean not null default false,
  constraint uk_links_code unique (code), constraint uk_links_idempotency unique (idempotency_key)
);
create table click_events (id bigint generated by default as identity primary key, link_id bigint not null, clicked_at timestamp with time zone not null, referrer varchar(512));
